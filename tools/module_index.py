#!/usr/bin/env python3
"""Generate docs/MODULE-INDEX.md and the dashboard's reading-time metadata from the module files.

  python tools/module_index.py --write   # regenerate generated sections
  python tools/module_index.py --check   # fail if generated sections are stale (used by CI)

Reading time = words outside fenced code blocks / 200 wpm (minimum 3). Labs and practice take extra time.
"""
import re
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
MODULE_FILE = re.compile(r"^(\d{2})\. (.+)\.md$")
GOAL_HEADING = re.compile(r"^#{2,3}\s*(?:Goal|Objectives?|Learning objectives?)\b.*$", re.I | re.M)
START, END = "/* MODULE-META:START */", "/* MODULE-META:END */"
TRACKS = [("Foundations", 1, 8), ("Core Concepts in an Authorized Lab", 9, 14), ("Active Directory", 15, 22),
          ("Post-Exploitation, Web and Wireless", 23, 26), ("Professional Practice", 27, 28),
          ("Modern Security Core (2026)", 29, 34), ("Secure Design, Detection and Governance", 35, 47),
          ("Cloud, Containers, AI, Response and Capstones", 48, 72), ("Security Operations and Resilience", 73, 86)]


def strip_code(text):
    return re.sub(r"^```.*?^```", "", text, flags=re.S | re.M)


def reading_minutes(text):
    words = len(re.findall(r"[A-Za-z0-9']+", strip_code(text)))
    return max(3, round(words / 200))


def extract_goal(text, limit=180):
    match = GOAL_HEADING.search(text)
    if not match:
        return ""
    body = text[match.end():]
    body = re.split(r"^#{1,6}\s", body, maxsplit=1, flags=re.M)[0]
    paragraph = " ".join(body.strip().split("\n\n")[0].split())
    paragraph = re.sub(r"[*_`]", "", paragraph)
    return paragraph if len(paragraph) <= limit else paragraph[: limit - 1].rstrip() + "…"


def track_for(number):
    return next(name for name, a, b in TRACKS if a <= number <= b)


def collect(root=ROOT):
    modules = []
    for path in sorted(root.iterdir()):
        m = MODULE_FILE.match(path.name)
        if m:
            text = path.read_text(encoding="utf-8")
            modules.append({"n": int(m.group(1)), "title": m.group(2), "file": path.name,
                            "minutes": reading_minutes(text), "goal": extract_goal(text), "track": track_for(int(m.group(1)))})
    return sorted(modules, key=lambda x: x["n"])


def render_markdown(modules):
    total = sum(m["minutes"] for m in modules)
    lines = ["# Module Index", "",
             "_Generated by `tools/module_index.py` — do not edit by hand. Run `make index` to refresh._", "",
             f"{len(modules)} modules · about {total // 60} h {total % 60} min of reading in total (reading time only; labs and practice take extra).", ""]
    current = None
    for m in modules:
        if m["track"] != current:
            current = m["track"]
            lines += [f"## {current}", "", "| # | Module | Reading time | Goal |", "|:-:|---|:-:|---|"]
        goal = m["goal"].replace("|", "\\|") or "—"
        lines.append(f"| {m['n']:02d} | [{m['title']}](../{quote(m['file'], safe='')}) | ~{m['minutes']} min | {goal} |")
        nxt = next((x for x in modules if x["n"] == m["n"] + 1), None)
        if nxt is None or nxt["track"] != current:
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_meta(modules):
    return f"{START}\nconst moduleMinutes = [{','.join(str(m['minutes']) for m in modules)}];\n{END}"


def apply_meta(html, modules):
    block = render_meta(modules)
    if START in html:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, html, flags=re.S)
    return html.replace("const moduleNames = [", block + "\nconst moduleNames = [", 1)


def check(root=ROOT):
    modules = collect(root)
    problems = []
    index = root / "docs" / "MODULE-INDEX.md"
    if not index.exists() or index.read_text(encoding="utf-8") != render_markdown(modules):
        problems.append("docs/MODULE-INDEX.md is stale; run `make index`")
    dash = (root / "dashboard" / "index.html").read_text(encoding="utf-8")
    if apply_meta(dash, modules) != dash:
        problems.append("dashboard reading-time metadata is stale; run `make index`")
    return problems


def write(root=ROOT):
    modules = collect(root)
    (root / "docs").mkdir(exist_ok=True)
    (root / "docs" / "MODULE-INDEX.md").write_text(render_markdown(modules), encoding="utf-8")
    dash_path = root / "dashboard" / "index.html"
    dash_path.write_text(apply_meta(dash_path.read_text(encoding="utf-8"), modules), encoding="utf-8")


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    if mode == "--write":
        write()
        print("Generated docs/MODULE-INDEX.md and dashboard metadata")
    else:
        issues = check()
        for issue in issues:
            print("FAIL:", issue)
        print("Module index up to date" if not issues else f"{len(issues)} problem(s)")
        sys.exit(1 if issues else 0)
